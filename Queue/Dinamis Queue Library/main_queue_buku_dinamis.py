from library_queue_buku_dinamis import QueueBukuDinamis

# Membuat objek queue buku
antrean_buku = QueueBukuDinamis()

print("===========================================")
print("    DEMO SIMULASI OTOMATIS QUEUE BUKU      ")
print("===========================================")

print("\n[1] Menambahkan 3 buku ke antrean...")
antrean_buku.tambah_buku("Algoritma & Pemrograman")
antrean_buku.tambah_buku("Basis Data")
antrean_buku.tambah_buku("Jaringan Komputer")

print("\n[2] Menampilkan isi antrean buku saat ini:")
antrean_buku.tampilkan_buku()

print("\n[3] Mengambil/memproses 1 buku dari paling depan (FIFO)...")
antrean_buku.ambil_buku()

print("\n[4] Menampilkan isi antrean buku setelah diproses:")
antrean_buku.tampilkan_buku()

print("\n===========================================")
print("           MASUK KE MENU INTERAKTIF         ")
print("===========================================")

while True:
  print("\n=== ANTREAN BUKU PERPUSTAKAAN (QUEUE) ===")
  print("1. Tambah buku ke antrean")
  print("2. Ambil/proses buku dari antrean")
  print("3. Tampilkan antrean buku")
  print("4. Keluar")

  pilihan = input("Pilih menu (1-4): ")

  if pilihan == "1":
    nama = input("Masukkan nama buku: ")
    antrean_buku.tambah_buku(nama)

  elif pilihan == "2":
    antrean_buku.ambil_buku()

  elif pilihan == "3":
    antrean_buku.tampilkan_buku()

  elif pilihan == "4":
    print("Program selesai. Terima kasih!")
    break

  else:
    print("Pilihan tidak valid!")