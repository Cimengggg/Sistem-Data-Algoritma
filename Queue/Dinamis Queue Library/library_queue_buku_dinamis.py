class QueueBukuDinamis:

  def __init__(self):
    # Wadah list kosong untuk menampung antrean buku secara dinamis
    self.data = []

  def kosong(self):
    # Mengecek apakah antrean buku kosong
    return len(self.data) == 0

  def tambah_buku(self, nama_buku):
    # Operasi Enqueue (Menambahkan buku di posisi paling belakang antrean)
    self.data.append(nama_buku)
    print(f"-> Buku '{nama_buku}' berhasil ditambahkan ke antrean.")

  def ambil_buku(self):
    # Operasi Dequeue (Mengambil buku dari posisi PALING DEPAN - Konsep FIFO)
    if self.kosong():
      print("-> Antrean buku kosong!")
    else:
      # Menggunakan pop(0) untuk mengambil dan menghapus elemen pertama (paling depan)
      buku = self.data.pop(0)
      print(f"-> Buku yang diproses/diambil: '{buku}'")

  def tampilkan_buku(self):
    # Menampilkan daftar antrean buku dari depan ke belakang
    if self.kosong():
      print("-> Antrean buku kosong!")
    else:
      print("Daftar Antrean Buku (Dari Depan ke Belakang):")
      for i in range(len(self.data)):
        print(f"  [Antrean ke-{i+1}] {self.data[i]}")